#!/usr/bin/env python3
"""CT40.A12.Solari.build_embedded.py

A11: also writes CT40.A12.Solari.icons.js (small data-URL copies of icons/*).

Browsers refuse to let a page opened by double-click (file://) read neighbouring
.json / .wav files. So the HTML first tries to read the real JSON files, and if
the browser blocks that it falls back to CT40.A12.Solari.embedded.js, which this
script writes: a copy of both JSON files plus the clack sample as base64.

Re-run after editing either JSON file or replacing audio/one.wav:
    python3 CT40.A12.Solari.build_embedded.py
(Or skip it: serve the folder with CT40.A12.Solari.serve.sh, or use the page's
"Load JSON" button, and the edited files are read directly.)
"""
import base64, json, os

HERE = os.path.dirname(os.path.abspath(__file__))

def load(name):
    with open(os.path.join(HERE, name)) as f:
        return json.load(f)

fields = load("CT40.A12.Solari.fields.json")
schedule = load("CT40.A12.Solari.schedule.json")
wav_path = os.path.join(HERE, fields.get("sound", {}).get("file", "audio/one.wav"))
with open(wav_path, "rb") as f:
    wav_b64 = base64.b64encode(f.read()).decode("ascii")

out = os.path.join(HERE, "CT40.A12.Solari.embedded.js")
with open(out, "w") as f:
    f.write("// CT40.A12.Solari.embedded.js -- GENERATED by CT40.A12.Solari.build_embedded.py; do not hand-edit.\n")
    f.write("// Fallback copy of the JSON files and clack sample for when the page is opened as a local file.\n")
    f.write("window.SOLARI_EMBEDDED = {\n")
    f.write("  fields: " + json.dumps(fields) + ",\n")
    f.write("  schedule: " + json.dumps(schedule) + ",\n")
    f.write("  soundBase64: \"" + wav_b64 + "\"\n};\n")
print(f"wrote {out} ({os.path.getsize(out)} bytes)")

# A11: small copies of the pictures in icons/ as data URLs, for the flap faces (the sun / moon of the AM/PM flap).
# A page opened by double-click may not paint its own folder's pictures into WebGL; data URLs are always allowed.
# The full-size originals in icons/ are used for the icon bands. Needs Pillow (pip install pillow).
from PIL import Image
import io, glob
icons = {}
for p in sorted(glob.glob(os.path.join(HERE, "icons", "*"))):
    if not p.lower().endswith((".webp", ".png", ".jpg", ".jpeg")):
        continue
    im = Image.open(p).convert("RGB")
    im.thumbnail((256, 256), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, "WEBP", quality=88)
    icons["icons/" + os.path.basename(p)] = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode("ascii")
out2 = os.path.join(HERE, "CT40.A12.Solari.icons.js")
with open(out2, "w") as f:
    f.write("// CT40.A12.Solari.icons.js -- GENERATED by CT40.A12.Solari.build_embedded.py; do not hand-edit.\n")
    f.write("// 256-px copies of the pictures in icons/, used on the flap faces (works when opened by double-click).\n")
    f.write("window.SOLARI_ICONS = " + json.dumps(icons, indent=1) + ";\n")
print(f"wrote {out2} ({os.path.getsize(out2)} bytes, {len(icons)} pictures)")
